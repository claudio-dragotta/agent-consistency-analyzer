# These are specialized artifact types for the Consistency & Conflict Analyzer

class ValidationReportArtifact(BaseModel):
    """
    Specialized artifact for validation reports produced by Agent 2.
    Contains the structured validation results.
    """
    artifact_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        alias="artifactId"
    )
    name: str = Field(default="Validation Report")
    description: str = Field(default="DDD model consistency and conflict analysis report")
    
    # Validation results
    validation_status: str = Field(
        ...,
        alias="validationStatus",
        description="Overall status: VALID, NEEDS_REVIEW, INVALID"
    )
    problems: List[Dict[str, Any]] = Field(
        default_factory=list,
        description="List of detected problems"
    )
    summary: Dict[str, Any] = Field(
        default_factory=dict,
        description="Summary statistics of validation"
    )
    
    metadata: Optional[Dict[str, Any]] = Field(None)

    class Config:
        populate_by_name = True

    def to_artifact(self) -> Artifact:
        """Convert to standard A2A Artifact."""
        return Artifact(
            artifact_id=self.artifact_id,
            name=self.name,
            description=self.description,
            parts=[Part.from_data({
                "validationStatus": self.validation_status,
                "problems": self.problems,
                "summary": self.summary
            })],
            metadata=self.metadata
        )


