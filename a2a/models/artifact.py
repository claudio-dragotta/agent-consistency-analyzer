"""
A2A Protocol - Artifact Model

Artifacts represent task outputs. They are the results produced by an agent
after processing a task.

Based on A2A Protocol Specification v0.3
"""

from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field
import uuid

from a2a.models.message import Part


class Artifact(BaseModel):
    """
    Artifacts represent task outputs.
    
    An artifact is a piece of output generated by an agent as a result 
    of processing a task. It can contain multiple parts (text, files, 
    structured data).
    """
    artifact_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        alias="artifactId",
        description="Unique identifier (UUID) for the artifact. Must be unique within a task."
    )
    name: Optional[str] = Field(
        None,
        description="A human readable name for the artifact"
    )
    description: Optional[str] = Field(
        None,
        description="A human readable description of the artifact"
    )
    parts: List[Part] = Field(
        ...,
        min_length=1,
        description="The content of the artifact. Must contain at least one part."
    )
    metadata: Optional[Dict[str, Any]] = Field(
        None,
        description="Optional metadata included with the artifact"
    )
    extensions: Optional[List[str]] = Field(
        None,
        description="The URIs of extensions that are present or contributed to this Artifact"
    )

    class Config:
        populate_by_name = True

    @classmethod
    def from_data(
        cls,
        data: Dict[str, Any],
        name: Optional[str] = None,
        description: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None
    ) -> "Artifact":
        """
        Factory method to create an Artifact from structured data.
        
        Args:
            data: The structured data (JSON object)
            name: Human readable name
            description: Human readable description
            metadata: Optional metadata
        """
        return cls(
            name=name,
            description=description,
            parts=[Part.from_data(data)],
            metadata=metadata
        )

    @classmethod
    def from_text(
        cls,
        text: str,
        name: Optional[str] = None,
        description: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None
    ) -> "Artifact":
        """
        Factory method to create an Artifact from text.
        
        Args:
            text: The text content
            name: Human readable name
            description: Human readable description
            metadata: Optional metadata
        """
        return cls(
            name=name,
            description=description,
            parts=[Part.from_text(text)],
            metadata=metadata
        )

    @classmethod
    def from_parts(
        cls,
        parts: List[Part],
        name: Optional[str] = None,
        description: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None
    ) -> "Artifact":
        """
        Factory method to create an Artifact from multiple parts.
        
        Args:
            parts: List of Part objects
            name: Human readable name
            description: Human readable description
            metadata: Optional metadata
        """
        return cls(
            name=name,
            description=description,
            parts=parts,
            metadata=metadata
        )

    def get_data_content(self) -> List[Dict[str, Any]]:
        """Extract all data content from artifact parts."""
        data_list = []
        for part in self.parts:
            if part.data is not None:
                data_list.append(part.data.data)
        return data_list

    def get_first_data(self) -> Optional[Dict[str, Any]]:
        """Get the first data part content, or None if no data parts."""
        for part in self.parts:
            if part.data is not None:
                return part.data.data
        return None

    def get_text_content(self) -> str:
        """Extract all text content from artifact parts."""
        texts = []
        for part in self.parts:
            if part.text is not None:
                texts.append(part.text)
        return "\n".join(texts)


