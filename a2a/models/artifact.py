class RefinedModelArtifact(BaseModel):
    """
    Specialized artifact for the refined domain model produced by Agent 2.
    This is the main output that goes to Agent 3.
    """
    artifact_id: str = Field(
        default_factory=lambda: str(uuid.uuid4()),
        alias="artifactId"
    )
    name: str = Field(default="Refined Domain Model")
    description: str = Field(default="Validated and corrected domain model ready for Agent 3")
    
